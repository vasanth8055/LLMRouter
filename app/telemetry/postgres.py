from __future__ import annotations

import json

from app.telemetry.models import InferenceTelemetry

CREATE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS inference_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    prompt_hash CHAR(64) NOT NULL,
    prompt_length INTEGER NOT NULL CHECK (prompt_length >= 0),
    canonical_model TEXT,
    provider_model TEXT,
    predicted_quality DOUBLE PRECISION,
    model_mapping_warning TEXT,
    routing_reason TEXT,
    input_tokens INTEGER,
    output_tokens INTEGER,
    estimated_cost_usd NUMERIC(18, 10),
    actual_latency_ms DOUBLE PRECISION,
    status TEXT NOT NULL CHECK (status IN ('success', 'failed')),
    error_type TEXT,
    error_message TEXT,
    attempted_models TEXT,
    failover BOOLEAN,
    policy_fallback BOOLEAN,
    retry_count INTEGER DEFAULT 0
)
"""

MIGRATION_SQL = (
    "ALTER TABLE inference_requests ADD COLUMN IF NOT EXISTS attempted_models TEXT",
    "ALTER TABLE inference_requests ADD COLUMN IF NOT EXISTS failover BOOLEAN",
    "ALTER TABLE inference_requests ADD COLUMN IF NOT EXISTS policy_fallback BOOLEAN",
    "ALTER TABLE inference_requests ADD COLUMN IF NOT EXISTS retry_count INTEGER DEFAULT 0",
)

CREATE_INDEXES_SQL = (
    "CREATE INDEX IF NOT EXISTS idx_inference_requests_created_at_id ON inference_requests (created_at DESC, id DESC)",
    "CREATE INDEX IF NOT EXISTS idx_inference_requests_canonical_model ON inference_requests (canonical_model)",
    "CREATE INDEX IF NOT EXISTS idx_inference_requests_status ON inference_requests (status)",
)

INSERT_TELEMETRY_SQL = """
INSERT INTO inference_requests (
    request_id, prompt_hash, prompt_length, canonical_model, provider_model,
    predicted_quality, model_mapping_warning, routing_reason, input_tokens,
    output_tokens, estimated_cost_usd, actual_latency_ms, status,
    error_type, error_message, attempted_models, failover, policy_fallback,
    retry_count
) VALUES (
    :request_id, :prompt_hash, :prompt_length, :canonical_model, :provider_model,
    :predicted_quality, :model_mapping_warning, :routing_reason, :input_tokens,
    :output_tokens, :estimated_cost_usd, :actual_latency_ms, :status,
    :error_type, :error_message, :attempted_models, :failover, :policy_fallback,
    :retry_count
)
ON CONFLICT (request_id) DO NOTHING
"""


def _decode_attempted_models(raw: object) -> list[str] | None:
    if raw is None:
        return None
    if isinstance(raw, list):
        return [str(item) for item in raw]
    if isinstance(raw, str):
        try:
            parsed = json.loads(raw)
        except ValueError:
            return None
        if isinstance(parsed, list):
            return [str(item) for item in parsed]
    return None


def _normalize_record_row(row: dict) -> dict:
    item = dict(row)
    if "attempted_models" in item:
        item["attempted_models"] = _decode_attempted_models(item["attempted_models"])
    return item


class PostgresTelemetryRepository:
    """Async SQLAlchemy Core repository; imports DB dependencies only when used."""

    def __init__(self, database_url: str) -> None:
        self.database_url = self._normalize_url(database_url)
        self._engine = None
        self._initialized = False

    @property
    def is_initialized(self) -> bool:
        return self._initialized

    @staticmethod
    def _normalize_url(url: str) -> str:
        if url.startswith("postgres://"):
            return "postgresql+asyncpg://" + url.removeprefix("postgres://")
        if url.startswith("postgresql://"):
            return "postgresql+asyncpg://" + url.removeprefix("postgresql://")
        return url

    def _get_engine(self):
        if self._engine is None:
            try:
                from sqlalchemy.ext.asyncio import create_async_engine
            except ImportError as exc:
                raise RuntimeError(
                    "PostgreSQL telemetry requires SQLAlchemy 2.x and asyncpg; install project dependencies."
                ) from exc
            self._engine = create_async_engine(self.database_url, pool_pre_ping=True)
        return self._engine

    async def initialize(self) -> None:
        from sqlalchemy import text

        async with self._get_engine().begin() as connection:
            await connection.execute(text(CREATE_TABLE_SQL))
            for index_sql in CREATE_INDEXES_SQL:
                await connection.execute(text(index_sql))
        self._initialized = True

    async def migrate(self) -> None:
        from sqlalchemy import text

        async with self._get_engine().begin() as connection:
            for migration_sql in MIGRATION_SQL:
                await connection.execute(text(migration_sql))

    async def save(self, record: InferenceTelemetry) -> None:
        from sqlalchemy import text

        if not self._initialized:
            raise RuntimeError(
                "PostgresTelemetryRepository is not initialized; call initialize() before saving telemetry."
            )
        payload = dict(record.__dict__)
        if payload.get("attempted_models") is not None:
            payload["attempted_models"] = json.dumps(payload["attempted_models"])
        engine = self._get_engine()
        async with engine.begin() as connection:
            await connection.execute(text(INSERT_TELEMETRY_SQL), payload)

    async def analytics_summary(self) -> dict:
        from sqlalchemy import text

        query = text("""
            SELECT COUNT(*) AS total_requests,
                   AVG(estimated_cost_usd) AS average_cost_usd,
                   AVG(actual_latency_ms) AS average_latency_ms,
                   COALESCE(
                       SUM(CASE WHEN status = 'failed' THEN 1 ELSE 0 END)::DOUBLE PRECISION
                       / NULLIF(COUNT(*), 0),
                       0
                   ) AS error_rate,
                   SUM(CASE WHEN policy_fallback THEN 1 ELSE 0 END)::DOUBLE PRECISION
                       / NULLIF(COUNT(policy_fallback), 0) AS fallback_rate,
                   SUM(CASE WHEN failover THEN 1 ELSE 0 END)::DOUBLE PRECISION
                       / NULLIF(COUNT(failover), 0) AS failover_rate
            FROM inference_requests
        """)
        async with self._get_engine().connect() as connection:
            row = (await connection.execute(query)).mappings().one()
            return dict(row)

    async def analytics_models(self) -> list[dict]:
        from sqlalchemy import text

        query = text("""
            SELECT canonical_model,
                   COUNT(*) AS request_count,
                   AVG(estimated_cost_usd) AS average_cost_usd,
                   SUM(estimated_cost_usd) AS total_cost_usd,
                   AVG(actual_latency_ms) AS average_latency_ms,
                   AVG(predicted_quality) AS average_predicted_quality
            FROM inference_requests
            WHERE canonical_model IS NOT NULL
            GROUP BY canonical_model
            ORDER BY request_count DESC, canonical_model ASC
        """)
        async with self._get_engine().connect() as connection:
            rows = await connection.execute(query)
            return [dict(row) for row in rows.mappings()]

    async def recent_requests(self, limit: int = 8) -> list[dict]:
        from sqlalchemy import text

        query = text("""
            SELECT request_id, created_at, prompt_hash, canonical_model, provider_model,
                   predicted_quality, input_tokens, output_tokens, estimated_cost_usd,
                   actual_latency_ms, status, attempted_models, failover, policy_fallback,
                   retry_count
            FROM inference_requests
            ORDER BY created_at DESC, id DESC
            LIMIT :limit
        """)
        async with self._get_engine().connect() as connection:
            rows = await connection.execute(query, {"limit": limit})
            return [_normalize_record_row(row) for row in rows.mappings()]

    async def request_page(
        self,
        *,
        limit: int,
        offset: int,
        model: str | None = None,
        status: str | None = None,
        search: str | None = None,
    ) -> tuple[int, list[dict]]:
        from sqlalchemy import text

        filters = """
            WHERE (CAST(:model AS TEXT) IS NULL OR canonical_model = CAST(:model AS TEXT))
              AND (CAST(:status AS TEXT) IS NULL OR status = CAST(:status AS TEXT))
              AND (CAST(:search AS TEXT) IS NULL OR request_id ILIKE ('%' || CAST(:search AS TEXT) || '%'))
        """
        params = {"model": model, "status": status, "search": search}
        count_query = text("SELECT COUNT(*) FROM inference_requests " + filters)
        page_query = text("""
            SELECT request_id, created_at, prompt_hash, canonical_model, provider_model,
                   predicted_quality, input_tokens, output_tokens, estimated_cost_usd,
                   actual_latency_ms, status, attempted_models, failover, policy_fallback,
                   retry_count
            FROM inference_requests
        """ + filters + " ORDER BY created_at DESC, id DESC LIMIT :limit OFFSET :offset")
        async with self._get_engine().connect() as connection:
            total = await connection.scalar(count_query, params)
            rows = await connection.execute(page_query, {**params, "limit": limit, "offset": offset})
            return int(total or 0), [_normalize_record_row(row) for row in rows.mappings()]

    async def close(self) -> None:
        self._initialized = False
        if self._engine is not None:
            await self._engine.dispose()
            self._engine = None
